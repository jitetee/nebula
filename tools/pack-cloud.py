#!/usr/bin/env python3
"""Pack the cloud (Firebase) settings so they are not readable as plain text.

  echo '{"db":"https://X-default-rtdb.firebaseio.com","key":"AIza...","project":"X"}' | python3 tools/pack-cloud.py

Writes scrambled chunk files to assets/cloud/ and rewrites the key-fragment block in lib/cloud.sh.
This hides the values from casual reading only. Real protection is your Firebase security rules
(see docs/database.rules.json).
"""
import sys, os, json, base64, random, secrets, re, glob
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = json.load(sys.stdin)
payload = "NCFG1\n%s\n%s\n%s\n" % (cfg["db"], cfg["key"], cfg["project"])
key = secrets.token_bytes(32)
blob = base64.b64encode(bytes(b ^ key[i % len(key)] for i, b in enumerate(payload.encode()))).decode()
def split(s, n):
    size = -(-len(s) // n); return [s[i:i+size] for i in range(0, len(s), size)]
chunks = split(blob, 5)
names = ["%04x" % random.getrandbits(16) for _ in chunks]
order = list(range(len(chunks))); random.shuffle(order)       # order[i] = which chunk is stored as file i
for old in glob.glob(os.path.join(root, "assets/cloud/*.dat")): os.remove(old)
files = []
for i, idx in enumerate(order):
    fn = "%s.dat" % names[i]; files.append(fn)
    open(os.path.join(root, "assets/cloud", fn), "w").write(chunks[idx])
seq = [files[order.index(i)][:-4] for i in range(len(chunks))]  # file names in chunk order
kh = key.hex(); kparts = split(kh, 4); kord = list(range(4)); random.shuffle(kord)
frag = [kparts[i] for i in kord]; kseq = [kord.index(i) for i in range(4)]
block = "# BEGIN-PACK (generated by tools/pack-cloud.py, do not edit)\n"
block += "CLOUD_SEQ=(%s)\n" % " ".join(seq)
block += "CLOUD_KF=(%s)\nCLOUD_KO=(%s)\n" % (" ".join(frag), " ".join(map(str, kseq)))
block += "# END-PACK"
p = os.path.join(root, "lib/cloud.sh"); s = open(p).read()
s = re.sub(r"# BEGIN-PACK.*?# END-PACK", lambda m: block, s, flags=re.S)
open(p, "w").write(s); print("packed %d chunks" % len(chunks))
