"""One palette for all of Nebula: shell, ant, jtlearn, Neovim, plugins.

`nebula palette ocean` writes $NEBULA_CFG/palette.json (+ palette.sh for the shell); every tool reads it at start.
Roles (256-colour index + hex): primary, second, accent, danger, border, soft, muted, text, bg.
"""
import json
import os
import sys

from . import paths

# name -> {role: xterm-256 index}, plus "bg" hex (the Neovim background tint)
PALETTES = {
    "nebula": dict(primary=48, second=120, accent=221, danger=203, border=35, soft=157, muted=245, text=255, bg="#0b120e"),
    "ocean":  dict(primary=45, second=117, accent=221, danger=203, border=31, soft=159, muted=245, text=255, bg="#0b1218"),
    "amber":  dict(primary=214, second=222, accent=48, danger=203, border=172, soft=223, muted=245, text=255, bg="#15110b"),
    "rose":   dict(primary=211, second=218, accent=221, danger=203, border=168, soft=225, muted=245, text=255, bg="#170d12"),
    "violet": dict(primary=141, second=183, accent=221, danger=203, border=98, soft=189, muted=245, text=255, bg="#110d18"),
    "mono":   dict(primary=255, second=250, accent=255, danger=203, border=240, soft=252, muted=244, text=255, bg="#101010"),
}
DEFAULT = "nebula"
ROLES = ("primary", "second", "accent", "danger", "border", "soft", "muted", "text")


def xterm_hex(n):
    if n < 16:
        base = ["000000", "800000", "008000", "808000", "000080", "800080", "008080", "c0c0c0",
                "808080", "ff0000", "00ff00", "ffff00", "0000ff", "ff00ff", "00ffff", "ffffff"]
        return "#" + base[n]
    if n >= 232:
        v = 8 + (n - 232) * 10
        return "#%02x%02x%02x" % (v, v, v)
    n -= 16
    lv = [0, 95, 135, 175, 215, 255]
    return "#%02x%02x%02x" % (lv[n // 36], lv[(n // 6) % 6], lv[n % 6])


def build(name):
    p = PALETTES[name]
    out = {"name": name, "bg": p["bg"]}
    for r in ROLES:
        out[r] = {"idx": p[r], "hex": xterm_hex(p[r])}
    return out


def _file():
    return os.path.join(paths.cfg(), "palette.json")


def current_name():
    try:
        n = json.load(open(_file(), encoding="utf-8")).get("name", DEFAULT)
    except (OSError, ValueError):
        n = os.environ.get("NEBULA_PALETTE", DEFAULT)
    return n if n in PALETTES else DEFAULT


def load():
    """The active palette (dict). Never raises: falls back to the default."""
    try:
        d = json.load(open(_file(), encoding="utf-8"))
        if all(r in d for r in ROLES):
            return d
    except (OSError, ValueError):
        pass
    return build(os.environ.get("NEBULA_PALETTE") if os.environ.get("NEBULA_PALETTE") in PALETTES else DEFAULT)


def idx(role):
    return load()[role]["idx"]


def hexcolor(role):
    return load()[role]["hex"]


def use(name):
    if name not in PALETTES:
        raise ValueError("palette must be one of: " + ", ".join(PALETTES))
    os.makedirs(paths.cfg(), exist_ok=True)
    d = build(name)
    with open(_file(), "w", encoding="utf-8") as f:
        json.dump(d, f, indent=1)
    sh = lambda i: "$'\\033[38;5;%dm'" % i
    with open(os.path.join(paths.cfg(), "palette.sh"), "w", encoding="utf-8") as f:   # sourced by lib/ui.sh
        f.write("# generated by `nebula palette %s`\nC_CYAN=%s\nC_GREEN=%s\nC_YELLOW=%s\nC_RED=%s\nC_BLUE=%s\nC_MAGENTA=%s\n" % (
            name, sh(d["primary"]["idx"]), sh(d["second"]["idx"]), sh(d["accent"]["idx"]),
            sh(d["danger"]["idx"]), sh(d["border"]["idx"]), sh(d["soft"]["idx"])))
    return d


def swatch(name):
    p = PALETTES[name]
    return "".join("\x1b[38;5;%dm■\x1b[0m" % p[r] for r in ("primary", "second", "accent", "danger", "border"))


def main(argv):
    if not argv or argv[0] in ("list", "ls"):
        cur = current_name()
        for n in PALETTES:
            print("%s %-8s %s" % ("●" if n == cur else "○", n, swatch(n)))
        return 0
    if argv[0] == "show":
        print(json.dumps(load()))
        return 0
    if argv[0] == "name":
        print(current_name())
        return 0
    n = argv[1] if argv[0] == "use" and len(argv) > 1 else argv[0]
    try:
        use(n)
    except ValueError as e:
        print(e, file=sys.stderr)
        return 2
    print("palette: %s %s  (new windows pick it up; Neovim on restart)" % (n, swatch(n)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
